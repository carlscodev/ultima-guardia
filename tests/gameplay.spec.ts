import { expect, test } from '@playwright/test'

test('menú, guía, arsenal y sonido funcionan en escritorio y móvil', async ({ page, isMobile }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  if (!isMobile) await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(page.locator('main')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByRole('button', { name: 'ENTRAR EN LA ZONA' })).toBeEnabled()
  await page.evaluate(() => document.fonts.ready)
  await expect.poll(() => page.locator('.menu-art img').evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: `/tmp/agent-browser/ultima-menu-${testInfo.project.name}.png` })
  await expect(page.locator('.command-menu')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

  await page.getByRole('button', { name: 'CÓMO JUGAR' }).click()
  await expect(page.getByRole('dialog', { name: 'CADA SEGUNDO CUENTA.' })).toBeVisible()
  await expect(page.getByText('Pulso defensivo', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'ARSENAL' }).click()
  await expect(page.getByRole('heading', { name: 'ESCOPETA K-12' })).toBeVisible()
  await page.getByRole('button', { name: 'ENTENDIDO. ESTOY LISTO.' }).click()
  await page.getByRole('button', { name: 'Silenciar sonido' }).click()
  await expect(page.getByRole('button', { name: 'Activar sonido' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Activar sonido' }).click()
  await expect(page.getByRole('button', { name: 'Silenciar sonido' })).toHaveAttribute('aria-pressed', 'false')
  expect(errors).toEqual([])
})

test('movimiento, armas, pulso, pausa y reinicio mantienen su estado correcto', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('main')).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: 'ENTRAR EN LA ZONA' }).click()
  await expect(page.locator('main')).toHaveAttribute('data-screen', 'playing')
  await expect.poll(() => page.evaluate(() => window.__UG_DEBUG__?.wave)).toBe(1)
  await page.screenshot({ path: `/tmp/agent-browser/ultima-game-${testInfo.project.name}.png` })

  const before = await page.evaluate(() => window.__UG_DEBUG__!.playerX)
  await page.keyboard.down('KeyD')
  await expect.poll(() => page.evaluate(() => window.__UG_DEBUG__!.playerX)).toBeGreaterThan(before + 8)
  await page.keyboard.up('KeyD')
  await page.keyboard.press('Digit2')
  await expect(page.getByRole('button', { name: 'Escopeta K-12' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Rifle M4' }).click()
  await expect(page.getByRole('button', { name: 'Rifle M4' })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: /Pulso defensivo, recargando/ })).toBeDisabled()
  await page.keyboard.press('KeyP')
  await expect(page.getByRole('button', { name: 'CONTINUAR OPERACIÓN' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => window.__UG_DEBUG__?.screen)).toBe('paused')
  const elapsed = await page.evaluate(() => window.__UG_DEBUG__!.elapsed)
  await page.waitForTimeout(300)
  expect(await page.evaluate(() => window.__UG_DEBUG__!.elapsed)).toBe(elapsed)
  await page.keyboard.press('Escape')
  await expect(page.locator('main')).toHaveAttribute('data-screen', 'playing')
  await page.getByRole('button', { name: 'Pausar', exact: true }).click()
  await page.getByRole('button', { name: 'VOLVER AL MENÚ' }).click()
  await expect(page.locator('main')).toHaveAttribute('data-screen', 'menu')
  await page.getByRole('button', { name: 'ENTRAR EN LA ZONA' }).click()
  await expect(page.getByRole('button', { name: 'Activar pulso defensivo' })).toBeEnabled()
  await expect(page.getByRole('progressbar', { name: 'Vida', exact: true })).toHaveAttribute('aria-valuenow', '100')
  await expect.poll(() => page.evaluate(() => window.__UG_DEBUG__?.kills)).toBe(0)
  await expect(page.getByRole('button', { name: 'Rifle M4' })).toHaveAttribute('aria-pressed', 'true')
  expect(errors).toEqual([])
})

test('el joystick táctil mueve al jugador y se libera al terminar el gesto', async ({ page, isMobile }) => {
  test.skip(!isMobile, 'El joystick solo se muestra con entrada táctil.')
  await page.goto('/')
  await page.getByRole('button', { name: 'ENTRAR EN LA ZONA' }).click()
  await expect(page.locator('main')).toHaveAttribute('data-screen', 'playing')
  const joystick = page.getByRole('group', { name: 'Joystick de movimiento' })
  await expect(joystick).toBeVisible()
  const box = (await joystick.boundingBox())!
  const before = await page.evaluate(() => window.__UG_DEBUG__!.playerX)
  await page.mouse.move(box.x + box.width / 2 + 28, box.y + box.height / 2)
  await page.mouse.down()
  await expect.poll(() => page.evaluate(() => window.__UG_DEBUG__!.playerX)).toBeGreaterThan(before + 5)
  await page.mouse.up()
  await expect(joystick.locator('.knob')).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  await page.getByRole('button', { name: 'Activar pulso defensivo' }).tap()
  await expect(page.getByRole('button', { name: /Pulso defensivo, recargando/ })).toBeDisabled()
})
